// Simple Faux Cryptographic hashing function for visual demonstration purposes
export function calculateRecordHash(record: Omit<PatientRecord, 'hash' | 'signature'>): string {
  const content = `${record.id}|${record.name}|${record.age}|${record.bloodType}|${record.diagnosis}|${record.medication}|${record.dosage}|${record.status}|${record.lastUpdated}|${record.updatedBy}|${record.prevHash}`;
  
  // Custom simple polynomial rolling hash for presentation UI
  let hashVal = 0;
  for (let i = 0; i < content.length; i++) {
    hashVal = (hashVal * 31 + content.charCodeAt(i)) & 0xFFFFFFFF;
  }
  return 'sha256_' + Math.abs(hashVal).toString(16).padStart(8, '0');
}

// Simple Faux HMAC Signature generator
export function generateHMACSignature(hash: string, secretKey: string): string {
  const content = `${hash}|${secretKey}`;
  let hashVal = 0;
  for (let i = 0; i < content.length; i++) {
    hashVal = (hashVal * 37 + content.charCodeAt(i)) & 0xFFFFFFFF;
  }
  return 'hmac_' + Math.abs(hashVal).toString(16).padStart(8, '0');
}

